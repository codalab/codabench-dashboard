"""
Build data.js for the static JS dashboard.

Reuses the keyword tagging in taxonomy.py and writes a single JavaScript
file that the dashboard loads via <script> (so index.html works when opened
directly from disk -- no server / CORS issues).

    python generate_data.py
"""

import json
import pandas as pd

from taxonomy import DOMAINS, SECTORS, CONFERENCES, COUNTRIES, tag_row

CSV_PATH = "codabench_competitions.csv"
OUT_PATH = "data.js"


def main():
    df = pd.read_csv(CSV_PATH)
    df["description"] = df["description"].fillna("")

    records = []
    for _, r in df.iterrows():
        domains, sectors, confs, countries = tag_row(r["title"], r["description"])
        records.append({
            "id": int(r["id"]),
            "title": r["title"],
            "organizer": r["organizer"],
            "url": r["url"],
            "domains": domains,
            "sectors": sectors,
            "conferences": confs,
            "countries": countries,
        })

    payload = {
        "competitions": records,
        "domains": list(DOMAINS.keys()),
        "sectors": list(SECTORS.keys()),
        "conferences": list(CONFERENCES.keys()),
        "countries": list(COUNTRIES.keys()),
    }

    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by generate_data.py -- do not edit by hand.\n")
        f.write("const DATA = ")
        json.dump(payload, f, ensure_ascii=False)
        f.write(";\n")

    print(f"Wrote {OUT_PATH}: {len(records)} competitions")


if __name__ == "__main__":
    main()
